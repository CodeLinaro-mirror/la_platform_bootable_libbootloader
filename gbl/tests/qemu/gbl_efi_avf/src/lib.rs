/// Test implementation of `GblEfiAvf`.
pub struct GblEfiAvfImpl;

impl GblEfiAvf for GblEfiAvfImpl {
    fn revision(&self) -> u64 {
        GBL_EFI_AVF_PROTOCOL_REVISION
    }

    fn read_vendor_dice_handover(&self, buffer: &mut [u8]) -> EfiResult<usize> {
        let mut buf = [0u8; 32];
        let handover_data: &[u8] = match semihosting::getenv(Some("GBL_DICE_ALG"), &mut buf)?.trim()
        {
            "kDiceKeyAlgorithmEd25519" => &DUMMY_VENDOR_HANDOVER_ED25519[..],
            "kDiceKeyAlgorithmP256" => &DUMMY_VENDOR_HANDOVER_P256[..],
            "kDiceKeyAlgorithmP384" => &DUMMY_VENDOR_HANDOVER_P384[..],
            "kDiceKeyAlgorithmMldsa65" => &DUMMY_VENDOR_HANDOVER_MLDSA65[..],
            "kDiceKeyAlgorithmMldsa87" => &DUMMY_VENDOR_HANDOVER_MLDSA87[..],
            _ => return Err(EfiError::InvalidParameter),
        };

        if buffer.len() < handover_data.len() {
            return Err(EfiError::BufferTooSmall(handover_data.len()));
        }

        buffer[..handover_data.len()].copy_from_slice(handover_data);
        Ok(handover_data.len())
    }

    fn read_secretkeeper_public_key(&self, _buffer: &mut [u8]) -> EfiResult<usize> {
        Err(EfiError::Unsupported)
    }
}
